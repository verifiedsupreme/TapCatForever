"""Model sizes for every Adventure enemy, so the Adventure page can fit each creature on screen.

UI_Adventure.lua measures each model in game (ModelScene actor bounding box). This table is the
fallback for when that measurement isn't available, and sets the small size differences between
creatures (a wolf a little shorter than an ogre).

For each creature display ID that GearData.lua's Adventure zones use:
  height, length (model X), width (model Y), bottom = CreatureModelData.GeoBox
  x CreatureModelData.ModelScale x CreatureDisplayInfo.CreatureModelScale, in yards,
  then CreatureDisplayInfo.CreatureModelScale on its own (the display scale). The game's measured
  bounding box may or may not include that display scale; the Adventure page uses it to tell.
GeoBox covers every animation, so it is a loose box: use it as a fallback, not as the main measure.

Source: the client's DB2 tables for WoW: Forever, exported as CSV by wago.tools:
  https://wago.tools/db2/CreatureModelData/csv?build=1.60.1.71037
  https://wago.tools/db2/CreatureDisplayInfo/csv?build=1.60.1.71037

usage: python3 tools/make_model_bounds.py <dir with CreatureModelData.csv and CreatureDisplayInfo.csv>
       -> ModelBoundsData.lua
"""
import csv, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
BUILD = "1.60.1.71037"


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    db = sys.argv[1]
    md = {r["ID"]: r for r in csv.DictReader(open(os.path.join(db, "CreatureModelData.csv"), encoding="utf-8"))}
    cdi = {r["ID"]: r for r in csv.DictReader(open(os.path.join(db, "CreatureDisplayInfo.csv"), encoding="utf-8"))}
    gear = open(os.path.join(ROOT, "GearData.lua"), encoding="utf-8").read()
    tiers = gear[gear.index("TCF.TIERS"):]
    ids = sorted(set(int(d) for d in re.findall(r'\{"[^"]+", (\d+)\}', tiers)))
    out = [
        "-- Generated by tools/make_model_bounds.py from WoW: Forever's DB2 tables (wago.tools, build %s)." % BUILD,
        "-- Do not edit by hand.",
        "local _, TCF = ...",
        "",
        "-- [creature display ID] = { height, length, width, bottom, display scale }",
        "-- sizes in yards (GeoBox x model scale x display scale); display scale = CreatureDisplayInfo.CreatureModelScale",
        "TCF.MODEL_BOUNDS = {",
    ]
    missing = []
    for d in ids:
        c = cdi.get(str(d))
        m = c and md.get(c["ModelID"])
        if not m:
            missing.append(d)
            continue
        g = [float(m["GeoBox_%d" % i]) for i in range(6)]
        ds = float(c["CreatureModelScale"] or 1)
        if ds <= 0:
            ds = 1.0
        s = ds * float(m["ModelScale"] or 1)
        if s <= 0:
            s = 1.0
        h, dx, dy, bz = (g[5] - g[2]) * s, (g[3] - g[0]) * s, (g[4] - g[1]) * s, g[2] * s
        if h <= 0:
            missing.append(d)
            continue
        out.append("  [%d] = { %.2f, %.2f, %.2f, %.2f, %.2f }," % (d, h, dx, dy, bz, ds))
    out.append("}")
    path = os.path.join(ROOT, "ModelBoundsData.lua")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("%d display IDs, %d written to ModelBoundsData.lua; not in this build: %s" % (len(ids), len(ids) - len(missing), missing))


if __name__ == "__main__":
    main()
