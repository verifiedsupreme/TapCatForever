#!/usr/bin/env python3
"""Builds NewsData.lua (the in-game patch notes) from CHANGELOG.md.

Each "## X.Y.Z" section becomes one entry. "**Heading**" lines become gold headings and
"- " lines become bullets. HIGHLIGHTS holds the one-line summary shown in the "What's new"
strip for big updates (a version listed there is a "big" update; others only appear on the
Patch notes page).

usage: python3 tools/make_news.py
"""
import os, re
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")

HIGHLIGHTS = {
    "1.5.3": "A new Dungeon Chest full of dungeon boss gear near your cat's level, a tidier Settings page, and small finds that bring your cat's weapon first.",
    "1.5.1": "Each class's cat now has its own Trade Gold and Renown, real legendaries can drop, raids give the new Raider's Hoard, and there is lots more gear.",
    "1.5.0": "Class professions with crafted gear, party cats with a tap bonus, a fishing dock, 33 new cat skins and the Compendium.",
}

def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'

def wow_text(md):
    out = []
    for line in md.strip().splitlines():
        line = line.rstrip()
        if not line:
            out.append("")
            continue
        m = re.match(r"^\*\*(.+)\*\*$", line)
        if m:
            out.append("|cffffd100" + m.group(1) + "|r")
            continue
        line = re.sub(r"\*\*(.+?)\*\*", r"\1", line)
        line = line.replace("|", "||")
        if line.startswith("- "):
            out.append("- " + line[2:])
        else:
            out.append(line)
    text = "\n".join(out)
    return re.sub(r"\n{3,}", "\n\n", text)

def main():
    md = open(os.path.join(ROOT, "CHANGELOG.md"), encoding="utf-8").read()
    parts = re.split(r"^## (\S+)\s*$", md, flags=re.M)
    entries = []
    for i in range(1, len(parts), 2):
        ver, body = parts[i], parts[i + 1]
        if not re.match(r"^\d+\.\d+\.\d+$", ver):
            continue
        entries.append((ver, wow_text(body)))
    lines = ["-- Generated by tools/make_news.py from CHANGELOG.md. Do not edit by hand.",
             "local _, TCF = ...", "TCF.NEWS = {"]
    for ver, text in entries:
        hl = HIGHLIGHTS.get(ver)
        lines.append("  { version = %s, highlight = %s, text = %s }," % (lua_str(ver), lua_str(hl) if hl else "nil", lua_str(text)))
    lines.append("}")
    open(os.path.join(ROOT, "NewsData.lua"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("NewsData.lua:", len(entries), "versions")

if __name__ == "__main__":
    main()
